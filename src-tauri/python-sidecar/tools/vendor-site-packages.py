#!/usr/bin/env python3
"""把 requirements.txt 的纯 Python wheel 打进 site-packages/。

用法（在 src-tauri/python-sidecar/ 下）：
    pip download -r requirements.txt --no-deps -d /tmp/wheels-v1
    python3 tools/vendor-site-packages.py /tmp/wheels-v1 site-packages

规则：只拷 .py 与数据文件（.pem/.txt/.md/.json），.so/.pyd/.dylib
一律丢掉——iOS 包里不能放桌面平台的二进制扩展；markupsafe 与
charset-normalizer 会自动走纯 Python 回退。dist-info 只留
METADATA 与 LICENSE*（署名与版本备查），其余丢掉。
"""
import shutil
import sys
import zipfile
from pathlib import Path

KEEP_SUFFIXES = {".py", ".pem", ".txt", ".md", ".json", ".pyi"}
KEEP_DIST_INFO = {"METADATA", "LICENSE", "LICENSE.txt", "LICENSE.md", "NOTICE"}


def vendor(wheels_dir: Path, out_dir: Path) -> None:
    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)
    wheels = sorted(wheels_dir.glob("*.whl"))
    if not wheels:
        raise SystemExit(f"no wheels in {wheels_dir}")
    dropped_binaries = []
    for wheel in wheels:
        with zipfile.ZipFile(wheel) as zf:
            for member in zf.namelist():
                if member.endswith("/"):
                    continue
                path = Path(member)
                if path.suffix in {".so", ".pyd", ".dylib"}:
                    dropped_binaries.append(member)
                    continue
                if ".dist-info/" in member:
                    if path.name not in KEEP_DIST_INFO:
                        continue
                elif path.suffix not in KEEP_SUFFIXES:
                    continue
                dest = out_dir / member
                dest.parent.mkdir(parents=True, exist_ok=True)
                with zf.open(member) as src, open(dest, "wb") as dst:
                    shutil.copyfileobj(src, dst)
        print(f"vendored {wheel.name}")
    if dropped_binaries:
        print("dropped binaries (pure-Python fallback applies):")
        for name in dropped_binaries:
            print(f"  {name}")


if __name__ == "__main__":
    vendor(Path(sys.argv[1]), Path(sys.argv[2]))
